// Unit test suite for CompilerClient and off-thread compilation architecture
import assert from 'node:assert';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { VFS } from '../src/vfs/vfs.js';
import { CompilerClient } from '../src/toolchain/compiler-client.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');

console.log('--- Running Compiler Client & Worker Architecture Unit Tests ---');

// Polyfill fetch for Node.js test environment
const nativeFetch = globalThis.fetch;
globalThis.fetch = async (url, ...args) => {
  if (typeof url === 'string' && (url.startsWith('http://') || url.startsWith('https://'))) {
    return nativeFetch(url, ...args);
  }
  let clean = String(url).replace(/^\/?sysroot\//, 'public/sysroot/').replace(/^\//, '');
  if (clean.startsWith('sysroot/')) clean = 'public/' + clean;
  const resolved = path.resolve(projectRoot, clean);
  const data = fs.readFileSync(resolved);
  return {
    ok: true,
    arrayBuffer: async () => data.buffer.slice(data.byteOffset, data.byteOffset + data.byteLength),
    text: async () => data.toString('utf-8')
  };
};

async function runTests() {
  const vfs = new VFS();
  let stdoutLogs = [];

  const client = new CompilerClient({
    basePath: '/sysroot/wasm',
    vfs,
    hostWrite: (str) => stdoutLogs.push(str),
  });

  // Test 1: Verify initialization
  console.log('Test 1: Verify CompilerClient initialization...');
  let progressUpdates = [];
  await client.init((status) => {
    progressUpdates.push(status);
  });
  assert.strictEqual(client.isReady, true, 'CompilerClient must be ready after init');
  assert.strictEqual(progressUpdates.length > 0, true, 'Progress updates must be reported');
  console.log('✓ CompilerClient initializes and reports progress');

  // Test 2: Verify compiling C source via executeCommand
  console.log('Test 2: Verify compiling C source via executeCommand...');
  const cSource = '#include <stdio.h>\nint main(void) {\n  printf("Hello from CompilerClient!\\n");\n  return 0;\n}\n';
  vfs.writeFile('/workspace/hello.c', cSource);

  let capturedOutput = '';
  const exitCode = await client.executeCommand({
    cmd: 'gcc',
    args: ['/workspace/hello.c', '-o', '/workspace/hello.wasm'],
    cwd: '/workspace',
    mode: 'c',
    write: (str) => { capturedOutput += str; },
  });

  if (exitCode !== 0) {
    console.error('Captured output:', capturedOutput);
  }
  assert.strictEqual(exitCode, 0, 'gcc compilation must exit with code 0');
  assert.strictEqual(vfs.exists('/workspace/hello.wasm'), true, 'Output binary must exist in VFS');
  const binBytes = vfs.readFile('/workspace/hello.wasm', false);
  assert.strictEqual(binBytes[0], 0x00, 'Magic byte 0 must be 0x00');
  assert.strictEqual(binBytes[1], 0x61, 'Magic byte 1 must be 0x61 (a)');
  assert.strictEqual(binBytes[2], 0x73, 'Magic byte 2 must be 0x73 (s)');
  assert.strictEqual(binBytes[3], 0x6d, 'Magic byte 3 must be 0x6d (m)');
  console.log('✓ C source compiles to valid WebAssembly binary via executeCommand');

  // Test 3: Verify make recipe execution through CompilerClient
  console.log('Test 3: Verify make execution through CompilerClient...');
  const makefileContent = `
CC = gcc
all: build/app.wasm

build/app.wasm: app.c
\tmkdir -p build
\t$(CC) app.c -o build/app.wasm
`;
  vfs.writeFile('/workspace/Makefile', makefileContent);
  vfs.writeFile('/workspace/app.c', 'int compute(int a) { return a * 2; }\nint main(void) { return compute(21); }\n');

  const makeExitCode = await client.executeCommand({
    cmd: 'make',
    args: ['all'],
    cwd: '/workspace',
  });

  assert.strictEqual(makeExitCode, 0, 'make must exit with code 0');
  assert.strictEqual(vfs.exists('/workspace/build/app.wasm'), true, 'Target binary must be generated by make');
  console.log('✓ Makefile execution via CompilerClient verified');

  // Test 4: Verify compatibility shims (compile, link, runTool)
  console.log('Test 4: Verify WasmToolchain compatibility shims...');
  assert.strictEqual(typeof client.compile, 'function');
  assert.strictEqual(typeof client.link, 'function');
  assert.strictEqual(typeof client.runTool, 'function');
  assert.strictEqual(client.hasFile('/workspace/hello.wasm'), true);
  const retrieved = client.getFile('/workspace/hello.wasm');
  assert.notStrictEqual(retrieved, null);
  console.log('✓ Compatibility shims verified');

  // Test 5: Verify kill cleanup
  console.log('Test 5: Verify kill cleanup...');
  assert.strictEqual(typeof client.kill, 'function');
  client.kill();
  assert.strictEqual(client.isCompiling, false);
  // Test 6: Verify decoupled sysroot utility mounting (mountSysrootUtilities)
  console.log('Test 6: Verify decoupled sysroot utility mounting...');
  const { mountSysrootUtilities } = await import('../src/vfs/sysroot.js');
  await mountSysrootUtilities(vfs, '/sysroot/wasm');
  assert.strictEqual(vfs.exists('/usr/bin/sqlite3'), true, '/usr/bin/sqlite3 must exist in VFS');
  const sqliteWasm = vfs.readFile('/usr/bin/sqlite3', false);
  assert.ok(sqliteWasm && sqliteWasm.length > 4, 'sqlite3 binary must have valid length');
  assert.strictEqual(sqliteWasm[0], 0x00, 'sqlite3 magic byte 0 must be 0x00');
  assert.strictEqual(sqliteWasm[1], 0x61, 'sqlite3 magic byte 1 must be 0x61 (a)');
  assert.strictEqual(sqliteWasm[2], 0x73, 'sqlite3 magic byte 2 must be 0x73 (s)');
  assert.strictEqual(sqliteWasm[3], 0x6d, 'sqlite3 magic byte 3 must be 0x6d (m)');
  console.log('✓ /usr/bin/sqlite3 is mounted via decoupled mountSysrootUtilities with valid WebAssembly binary');

  console.log('--- All Compiler Client Unit Tests Passed ---');
}

runTests().catch((err) => {
  console.error('Test failed:', err);
  process.exit(1);
});

